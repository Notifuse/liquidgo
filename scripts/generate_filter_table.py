# Generates liquid/standard_filter_table.go: a filter for each exported method
# of StandardFilters, named in snake_case. Run from the root of the repository
# after adding or changing a standard filter:
#
#   python3 scripts/generate_filter_table.py && gofmt -w liquid/standard_filter_table.go
#
# TestTheStandardFilterTableFollowsStandardFilters fails when the table is out
# of date.
import re,glob,sys
methods=[]
for f in sorted(glob.glob('liquid/*.go')):
    if f.endswith('_test.go') or f.endswith('standard_filter_table.go'): continue
    for m in re.finditer(r'^func \(sf \*StandardFilters\) ([A-Z]\w*)\(([^)]*)\) ([^{]*)\{', open(f).read(), re.M):
        params=[p.strip() for p in m.group(2).split(',') if p.strip()]
        methods.append((m.group(1), len(params), m.group(3).strip()))
def snake(n):
    s=re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', n)
    s=re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', s)
    return s.lower()
override={'TruncateWords':'truncatewords'}
# Ruby's defaults of the arguments a filter may be called without, by the
# index of the argument after the input.
defaults={'Join':{0:'" "'},'Truncate':{0:'50',1:'"..."'},'TruncateWords':{0:'15',1:'"..."'},
          'Replace':{1:'""'},'ReplaceFirst':{1:'""'},'Round':{0:'0'},'Default':{0:'""'}}
# Ruby's arity of each filter, the input included: the required arguments
# and the optional ones (lib/liquid/standardfilters.rb of Shopify Liquid
# 5.14.0). A filter given fewer than the required raises Ruby's ArgumentError.
ruby_arity={'abs':(1,0), 'append':(2,0), 'apply_operation':(3,0), 'at_least':(2,0), 'at_most':(2,0), 'base64_decode':(1,0), 'base64_encode':(1,0), 'base64_url_safe_decode':(1,0), 'base64_url_safe_encode':(1,0), 'capitalize':(1,0), 'ceil':(1,0), 'compact':(1,1), 'concat':(2,0), 'date':(2,0), 'default':(1,2), 'divided_by':(2,0), 'downcase':(1,0), 'escape':(1,0), 'escape_once':(1,0), 'filter_array':(3,1), 'find':(2,1), 'find_index':(2,1), 'first':(1,0), 'floor':(1,0), 'h':(1,0), 'has':(2,1), 'initialize':(2,0), 'join':(1,1), 'last':(1,0), 'lstrip':(1,0), 'map':(2,0), 'minus':(2,0), 'modulo':(2,0), 'newline_to_br':(1,0), 'nil_safe_casecmp':(2,0), 'nil_safe_compare':(2,0), 'plus':(2,0), 'prepend':(2,0), 'raise_property_error':(1,0), 'reject':(2,1), 'remove':(2,0), 'remove_first':(2,0), 'remove_last':(2,0), 'replace':(2,1), 'replace_first':(2,1), 'replace_last':(3,0), 'reverse':(1,0), 'round':(1,1), 'rstrip':(1,0), 'size':(1,0), 'slice':(2,1), 'sort':(1,1), 'sort_natural':(1,1), 'split':(2,0), 'squish':(1,0), 'strip':(1,0), 'strip_html':(1,0), 'strip_newlines':(1,0), 'sum':(1,1), 'times':(2,0), 'truncate':(1,2), 'truncatewords':(1,2), 'try_coerce_encoding':(1,0), 'uniq':(1,1), 'upcase':(1,0), 'url_decode':(1,0), 'url_encode':(1,0), 'where':(2,1)}
# The methods take nil for their default: an argument a template gives as nil
# is passed as Ruby reads it, an empty string (nil.to_s), which is also not an
# integer for a length.
nil_as_empty={'Join':[0],'Truncate':[0,1],'TruncateWords':[0,1]}
out=['// Code generated by scripts/generate_filter_table.py from the methods of','// StandardFilters; DO NOT EDIT.','','package liquid','',
'// standardFilters are the filters of every environment: each calls its',
'// method of StandardFilters, with Ruby\'s default for an argument it is',
'// not given, or nil when Ruby has none, and an argument given as nil as',
'// Ruby reads it; an argument too many or too few is an ArgumentError, and the error',
'// a method returns is the filter\'s error.',
'var standardFilters = map[string]FilterFunc{']
for name,n,res in sorted(methods, key=lambda m: override.get(m[0], snake(m[0]))):
    fname=override.get(name, snake(name))
    extra=n-1
    call='ctx.standard().%s(input%s)'%(name, ''.join(', a%d'%i for i in range(extra)))
    two=res.startswith('(')
    body=[]
    req,opt=ruby_arity[fname]
    body.append('\t\tif len(args) > %d {'%extra)
    body.append('\t\t\treturn nil, tooManyFilterArgs(len(args)+1, %d)'%n)
    body.append('\t\t}')
    if req>1:
        body.append('\t\tif len(args) < %d {'%(req-1))
        body.append('\t\t\treturn nil, tooFewFilterArgs(len(args)+1, %d, %d)'%(req,req+opt))
        body.append('\t\t}')
    for i in range(extra):
        body.append('\t\ta%d := filterArg(args, %d)'%(i,i))
    for i,d in sorted(defaults.get(name,{}).items()):
        body.append('\t\tif len(args) < %d {'%(i+1)); body.append('\t\t\ta%d = %s'%(i,d))
        if i in nil_as_empty.get(name,[]):
            body.append('\t\t} else if a%d == nil {'%i); body.append('\t\t\ta%d = ""'%i)
        body.append('\t\t}')
    if two: body.append('\t\treturn %s'%call)
    else: body.append('\t\treturn %s, nil'%call)
    out.append('\t%s: func(ctx *Context, input interface{}, args ...interface{}) (interface{}, error) {'%('"%s"'%fname))
    out+=body
    out.append('\t},')
out.append('}')
open('liquid/standard_filter_table.go','w').write('\n'.join(out)+'\n')
print(len(methods),'filters')
